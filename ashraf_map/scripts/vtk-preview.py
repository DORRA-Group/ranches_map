import vtk,os
p=os.path.abspath(os.path.join(os.path.dirname(__file__),'../public/models/ranches-garden-fountain.glb'))
out=os.path.abspath(os.path.join(os.path.dirname(__file__),'../previews/fountain-3d-preview.png'))
w=vtk.vtkRenderWindow();w.SetOffScreenRendering(1);w.SetSize(1100,860)
importer=vtk.vtkGLTFImporter();importer.SetFileName(p);importer.SetRenderWindow(w)
importer.Update()
r=importer.GetRenderer()
r.SetBackground(.94,.94,.925)
cam=r.GetActiveCamera();cam.SetPosition(18,-24,31);cam.SetFocalPoint(0,0,0.5);cam.SetViewUp(0,0,1);cam.ParallelProjectionOn();cam.SetParallelScale(15)
r.ResetCameraClippingRange()
w.Render()
s=vtk.vtkWindowToImageFilter();s.SetInput(w);s.Update()
wrt=vtk.vtkPNGWriter();wrt.SetInputConnection(s.GetOutputPort());wrt.SetFileName(out);wrt.Write()
print('Wrote',out)
