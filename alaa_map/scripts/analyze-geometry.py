#!/usr/bin/env python3
"""Measure classification agreement between the Ashraf GIS and Alaa scene.

Requires Shapely (``python3 -m pip install shapely``). The analysis uses a local
metre projection suitable for the small Ranches site and writes a Markdown
report beside the application README.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

try:
    from shapely.geometry import shape
    from shapely.ops import transform, unary_union
    from shapely.validation import make_valid
except ImportError as error:
    raise SystemExit("Shapely is required: python3 -m pip install shapely") from error


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "public" / "data"
OUTPUT = ROOT / "GEOMETRY_RECONCILIATION.md"
CENTER_LNG, CENTER_LAT = 30.86, 30.095
METRES_LNG = 111_320 * math.cos(math.radians(CENTER_LAT))
METRES_LAT = 110_574


def load(name: str) -> dict:
    with (DATA / name).open(encoding="utf-8") as source:
        return json.load(source)


def merged(collection: dict, kind: str):
    geometries = [
        make_valid(shape(feature["geometry"]))
        for feature in collection["features"]
        if feature.get("properties", {}).get("kind") == kind
    ]
    geographic = unary_union(geometries)
    return transform(
        lambda x, y, z=None: ((x - CENTER_LNG) * METRES_LNG, (y - CENTER_LAT) * METRES_LAT),
        geographic,
    )


def comparison(gis_geometry, alaa_geometry) -> dict[str, float]:
    overlap = gis_geometry.intersection(alaa_geometry).area
    union = gis_geometry.union(alaa_geometry).area
    return {
        "gis": gis_geometry.area,
        "alaa": alaa_geometry.area,
        "overlap": overlap,
        "gis_covered": overlap / gis_geometry.area * 100,
        "alaa_covered": overlap / alaa_geometry.area * 100,
        "iou": overlap / union * 100,
    }


def main() -> None:
    gis = load("site-gis.json")
    alaa = load("streets.json")
    gis_geometries = {kind: merged(gis, kind) for kind in ("boundary", "plot", "landscape", "water", "road", "parking")}
    matches = {
        "Roads": comparison(gis_geometries["road"], merged(alaa, "carriageway")),
        "Parking": comparison(gis_geometries["parking"], merged(alaa, "parking")),
        "Landscape": comparison(gis_geometries["landscape"], merged(alaa, "green")),
    }

    conflicts: list[tuple[str, str, float]] = []
    classifications = ("plot", "landscape", "road", "parking")
    for index, first in enumerate(classifications):
        for second in classifications[index + 1 :]:
            area = gis_geometries[first].intersection(gis_geometries[second]).area
            if area >= 1:
                conflicts.append((first, second, area))

    rows = "\n".join(
        f"| {name} | {values['gis']:,.0f} | {values['alaa']:,.0f} | {values['overlap']:,.0f} | "
        f"{values['gis_covered']:.1f}% | {values['alaa_covered']:.1f}% | {values['iou']:.1f}% |"
        for name, values in matches.items()
    )
    conflict_rows = "\n".join(f"| {first} / {second} | {area:,.1f} m² |" for first, second, area in conflicts) or "| None ≥ 1 m² | 0 m² |"
    report = f"""# Geometry reconciliation

Generated by `python3 scripts/analyze-geometry.py` from `public/data/site-gis.json` and `public/data/streets.json`.

## Classification comparison

| Surface | Ashraf GIS area (m²) | Alaa area (m²) | Intersection (m²) | GIS covered by Alaa | Alaa covered by GIS | IoU |
|---|---:|---:|---:|---:|---:|---:|
{rows}

The datasets share the same coordinate placement, but they do not describe identical surfaces. Area differences are therefore classification/derivation differences, not a single global offset. In **Combined** mode the Ashraf GIS is authoritative for classified ground.

## GIS internal conflicts

| Class pair | Overlap |
|---|---:|
{conflict_rows}

Water is intentionally contained by the landscape source and is rendered above it. Sub-metre numerical slivers are ignored.

## Reconciliation policy

- **Ashraf GIS owns:** project boundary, plots, landscape, water, asphalt road surface and parking surface.
- **Alaa presentation owns:** villas, paths, sidewalks, islands, kerbs, markings, wall, trees, cars, lights, shadows, fountain, labels, tour and navigation.
- **Alaa-only mode retains:** Alaa carriageway, parking and green surfaces for direct visual comparison.
- Geometry without a verified GIS equivalent remains explicitly illustrative until a source layer is imported.
"""
    OUTPUT.write_text(report, encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
